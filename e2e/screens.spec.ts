import { expect, test } from "@playwright/test"
import { confirmEmail, signUp, uniqueEmail } from "./helpers"

// Screenshots of the milestone screens for a design review. Run on demand:
//   SCREENS=1 pnpm e2e screens.spec.ts   → e2e/screens/*.png (not committed)
test.skip(!process.env.SCREENS, "set SCREENS=1 to capture screenshots")

test("capture milestone screens", async ({ page }, info) => {
  const shot = (name: string) => page.screenshot({ path: `e2e/screens/${info.project.name}-${name}.png`, fullPage: true })
  const email = uniqueEmail("screens")
  await signUp(page, email)
  await confirmEmail(email)
  await page.reload()
  await shot("1-who")
  await page.getByText("Business", { exact: true }).click()
  await page.getByRole("button", { name: /Continue/ }).click()
  await page.getByText("Product showcase", { exact: true }).click()
  await shot("2-type")
  await page.getByRole("button", { name: /Continue/ }).click()
  await page.getByLabel("Product or website link").fill("https://example.com/serum")
  await shot("3-input")
  await page.getByRole("button", { name: /Continue/ }).click()
  await page.getByRole("switch", { name: "Add my logo and colors" }).click()
  await shot("4-style")
  await page.getByRole("button", { name: /Continue/ }).click()
  await shot("5-review-choices")
  await page.getByRole("button", { name: "Make video" }).click()
  await page.waitForURL(/\/app\/videos\/job_/)
  await page.waitForTimeout(4000)
  await shot("6-progress")
  await page.waitForURL(/\/review$/, { timeout: 90_000 })
  await expect(page.getByLabel("Title")).toHaveValue(/Stub/)
  await shot("7-review")
  await page.getByRole("button", { name: /^Approve/ }).first().click()
  await shot("8-connect")
  await page.getByRole("link", { name: "Connect YouTube" }).click()
  await page.waitForURL(/\/review$/)
  await expect(page.getByText(/^Approved\. Posting/).first()).toBeVisible()
  await shot("9-approved")
  await page.goto("/app/videos")
  await shot("10-videos")
})
